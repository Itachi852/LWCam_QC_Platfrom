-- Upgrade note (2026-07-21 schema v2)
-- ============================================================================

/*
This file uses CREATE TABLE IF NOT EXISTS throughout, so re-running it
against an existing database only adds app_settings and does nothing else.
Per the project's fresh-v1 convention (R&D, no shipped installs), the
expected upgrade path for the v2 changes below is DROP AND RECREATE the
database from this file:

  - users.device_id / users.roles (new nullable/defaulted columns — safe to
    add either way, but a fresh DB is simplest).
  - projects.project_key (NOT NULL UNIQUE — cannot be added to a table with
    existing rows without a backfill). If live project data must survive a
    schema bump instead of a fresh recreate, backfill every existing row's
    project_key from that project's LWCAM/LWCam Admin JSON store record
    BEFORE the first push after the upgrade, or the push will attempt to
    insert duplicates that fail the project_id UNIQUE constraint.
  - 2026-07-21 (later, same day): users.device_id, projects.project_id and
    projects.project_name switched from full UNIQUE constraints to PARTIAL
    unique indexes (WHERE is_deleted = FALSE) so a soft-deleted row's
    values can be reused by a new account/project — a full UNIQUE made
    delete-then-recreate wedge LWCam Admin's push permanently.
    country_location_code stays full UNIQUE (FK target from devices);
    LWCam Admin's projectSoftDeleteSql frees it by rewriting it to
    '~deleted~<id>' instead. Same drop-and-recreate upgrade path.
*/