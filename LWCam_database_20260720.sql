-- ============================================================================
-- App settings (LWCam Admin-managed key/value store)
-- ============================================================================

/*
Shared configuration that used to live only in the NAS users-store JSON:
metadata keying on/off, remote-shutter config, the store-wide default temp
password, and the SuperAdmin password override. LWCam Admin is the only
writer; LWCAM pulls this table read-only alongside users/projects.

Keys in use: metadata_keying_enabled ('true'/'false'), shutter_keybind,
shutter_method, shutter_tap_x_percent, shutter_tap_y_percent,
default_temp_password_hash (bcrypt), superadmin_password_hash (bcrypt
override — an absent row means "use the factory hash").
*/

CREATE TABLE IF NOT EXISTS public.app_settings (
    key         VARCHAR(255) PRIMARY KEY,

    value       VARCHAR(10800),

    updated_at  TIMESTAMPTZ(3) NOT NULL
                    DEFAULT clock_timestamp()
);


-- ============================================================================
-- Indexes
-- ============================================================================


-- Users

CREATE INDEX IF NOT EXISTS idx_users_created_by
    ON public.users(created_by);

CREATE INDEX IF NOT EXISTS idx_users_updated_by
    ON public.users(updated_by);

/* Unique among LIVE accounts only: a soft-deleted account keeps its
   device_id for audit, but the id must be reassignable to a new account —
   a full UNIQUE would make delete-then-reassign fail forever. */
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_device_id_live
    ON public.users(device_id)
    WHERE is_deleted = FALSE AND device_id IS NOT NULL;


-- Projects

CREATE INDEX IF NOT EXISTS idx_projects_created_by
    ON public.projects(created_by);

CREATE INDEX IF NOT EXISTS idx_projects_updated_by
    ON public.projects(updated_by);

/* Unique among LIVE projects only, same rationale as
   uq_users_device_id_live: a deleted project's human-editable label/name
   must be reusable by a new project (which gets a fresh project_key).
   project_key itself stays a full UNIQUE column constraint — it is the
   upsert conflict target and is never reused. country_location_code also
   stays a full UNIQUE column constraint (it is an FK target — see the
   column comment for how soft delete frees it instead). */
CREATE UNIQUE INDEX IF NOT EXISTS uq_projects_project_id_live
    ON public.projects(project_id)
    WHERE is_deleted = FALSE;

CREATE UNIQUE INDEX IF NOT EXISTS uq_projects_project_name_live
    ON public.projects(project_name)
    WHERE is_deleted = FALSE;


-- Devices

CREATE INDEX IF NOT EXISTS idx_devices_country_location_code
    ON public.devices(country_location_code);

CREATE INDEX IF NOT EXISTS idx_devices_user_id
    ON public.devices(user_id);


-- User-project-role assignments

CREATE INDEX IF NOT EXISTS idx_user_projects_project_id
    ON public.user_projects(project_id);

CREATE INDEX IF NOT EXISTS idx_user_projects_role_id
    ON public.user_projects(role_id);


-- Capture boxes

CREATE INDEX IF NOT EXISTS idx_capture_boxes_device_id
    ON public.capture_boxes(device_id);

CREATE INDEX IF NOT EXISTS idx_capture_boxes_user_id
    ON public.capture_boxes(user_id);


/*
A separate project_id index is unnecessary because the following
unique constraint already creates an index beginning with project_id:

UNIQUE (project_id, box_name)
*/


-- Capture folders

CREATE INDEX IF NOT EXISTS idx_capture_folders_device_id
    ON public.capture_folders(device_id);


/*
A separate box_id index is unnecessary because the following
unique constraint already creates an index beginning with box_id:

UNIQUE (box_id, folder_seq)
*/


-- Capture images

CREATE INDEX IF NOT EXISTS idx_capture_images_image_name
    ON public.capture_images(image_name);

CREATE INDEX IF NOT EXISTS idx_capture_images_device_id
    ON public.capture_images(device_id);


/*
A separate folder_id index is unnecessary because the following
unique constraint already creates an index beginning with folder_id:

UNIQUE (folder_id, image_name)
*/


-- Rework records

CREATE INDEX IF NOT EXISTS idx_rework_logs_image_id
    ON public.rework_logs(image_id);

CREATE INDEX IF NOT EXISTS idx_rework_logs_folder_id
    ON public.rework_logs(folder_id);

CREATE INDEX IF NOT EXISTS idx_rework_logs_assigned_uid
    ON public.rework_logs(assigned_uid);


/*
App settings needs no secondary index — it is looked up and iterated
entirely by its own primary key (key).
*/


